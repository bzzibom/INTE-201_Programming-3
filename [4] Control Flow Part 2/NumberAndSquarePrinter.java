public class NumberAndSquarePrinter {
    public static void main(String[] args) {
        
        System.out.println("===== NUMBER AND SQUARE PRINTER (1-10)=====");
        for (int i = 1; i <= 10; i++) {
            System.out.println("Number: " + i + " | Square: " + (i * i));
        }
        System.out.println("\n===== NUMBER AND SQUARE PRINTER (1-20)=====");
        for (int i = 1; i <= 20; i++) {
            System.out.println("Number: " + i + " | Square: " + (i * i));
        }
    }
}
